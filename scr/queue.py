"""Queue views. queues/*.md are regenerated from records + graph; never a source of truth."""
from __future__ import annotations

from pathlib import Path

from .graph import Graph
from .score import rank_ready

INBOX_MARK = "## Inbox"
ESCALATED_MARK = "## Escalated by the Steward — your hand is needed"
# A task in one of these statuses waits on Omri whatever its `queue` field says: the Steward has stopped
# (escalated) or handed over (omri_queue). Before T-0109 only `queue: omri` items were listed, so the
# hand merges of T-0076/T-0059/T-0058 (2026-09-21) were invisible in queues/omri.md.
ESCALATED_STATUSES = {"escalated", "omri_queue"}
NO_REVIEW = "no review.md"
NO_DECISION = "no Decision line in review.md"
TEMPLATE_DECISION = "accepted | returned (feedback below) | escalated (Gate N, reason)"   # templates/review.md:13, unfilled
UNFILLED_DECISION = "review.md Decision not written (still the template line)"


def decision_line(task_dir: Path) -> str:
    """The Steward's verdict as written: the first paragraph after `## Decision` in review.md, joined into one
    line (a Decision wrapped over several lines, as T-0067's, must not be cut mid-sentence). `no review.md` when
    the file is absent; `no Decision line in review.md` when the heading is missing or empty; a template line
    left unfilled is named as such rather than shown as if it were a verdict."""
    p = task_dir / "review.md"
    if not p.is_file():
        return NO_REVIEW
    lines = p.read_text(encoding="utf-8", errors="replace").splitlines()
    for i, ln in enumerate(lines):
        if ln.strip().lower() == "## decision":
            para: list[str] = []
            for nxt in lines[i + 1:]:
                if nxt.startswith("#") or (para and not nxt.strip()):
                    break
                if nxt.strip():
                    para.append(nxt.strip())
            text = " ".join(para)
            if not text:
                return NO_DECISION
            return UNFILLED_DECISION if text == TEMPLATE_DECISION else text
    return NO_DECISION


def escalated_tasks(g: Graph) -> list:
    """Open tasks that wait on Omri's hand by status, excluding `queue: omri` items (listed as decisions already)."""
    return sorted((t for t in g.tasks.values() if t.status in ESCALATED_STATUSES and t.rec.get("queue") != "omri"), key=lambda t: t.id)


def render_scribers(g: Graph, weights: dict, limits: dict) -> str:
    rows = rank_ready(g, weights, "scribers")
    cap = int(limits.get("concurrency", 3))
    chosen = g.independent_set([r["task"] for r in rows], cap)
    lines = [
        "# Scriber queue", "",
        "Regenerated by `scr refresh` — view only; edit task records, not this file.", "",
        f"Next dispatch (cap {cap}, conflict-free): " + (", ".join(chosen) if chosen else "—"), "",
        "| rank | task | score | unlock | path | breadth | verif | risk | att | title |",
        "|---:|---|---:|---:|---:|---:|---:|---:|---:|---|",
    ]
    for i, r in enumerate(rows, 1):
        t = g.tasks[r["task"]]
        tm = r["terms"]
        flag = " ⚑stmt" if ((t.rec.get("scope") or {}).get("may_touch_statements")) else ""
        lines.append(f"| {i} | {r['task']} | {r['score']:.2f} | {tm['unlock_value']:.1f} | {tm['critical_path_share']:.2f} | "
                     f"{int(tm['blocking_breadth'])} | {tm['verifiability']:.1f} | {tm['risk']:.1f} | {int(tm['attempts'])} | {t.rec.get('title','')}{flag} |")
    others = [t for t in g.tasks.values() if t.rec.get("queue") == "scribers" and t.is_open and t.id not in {r["task"] for r in rows} and t.rec.get("kind") != "milestone"]
    if others:
        lines += ["", "## Not ready", ""]
        for t in sorted(others, key=lambda t: t.id):
            bl = [a for a in t.rec.get("blocked_by") or [] if a in g.tasks and not g.tasks[a].is_done]
            lines.append(f"- {t.id} `{t.status}` {t.rec.get('title','')}" + (f" — waits on {', '.join(bl)}" if bl else ""))
    return "\n".join(lines) + "\n"


def render_omri(g: Graph, existing: str | None) -> str:
    items = [t for t in g.tasks.values() if t.rec.get("queue") == "omri" and t.is_open]
    items.sort(key=lambda t: -len([d for d in g.descendants(t.id) if g.tasks[d].is_open]))
    lines = ["# Omri's queue", "", "Regenerated by `scr refresh` — answer items in the UI (or `scr answer`); the Concierge applies answers.", ""]
    for t in items:
        waiting = [d for d in g.descendants(t.id) if g.tasks[d].is_open]
        ms = [d for d in waiting if g.tasks[d].rec.get("kind") == "milestone"]
        lines.append(f"### {t.id} · {t.rec.get('kind')} · {t.rec.get('title','')}")
        lines.append(f"Waiting on this: {len(waiting) - len(ms)} tasks, {len(ms)} milestones. Status `{t.status}`.")
        lines.append(f"Brief: `{t.dir.name}/spec.md`")
        lines.append("")
        lines.append("Answer:")
        lines.append("")
    # Escalated scriber tasks: a to-do list for Omri's hand. What to do is the review's Decision line, on the
    # line itself; no `Answer:` slot (the Concierge applies answers only to queue: omri items, answers.py:37).
    esc = escalated_tasks(g)
    if esc:
        lines += [ESCALATED_MARK, "",
                  "Each of these stopped at the Steward and waits on you (status `escalated` or `omri_queue`); the Decision line is what to do. "
                  "They stay here until the task leaves those statuses.", ""]
        for t in esc:
            lines.append(f"### {t.id} · {t.rec.get('kind')} · {t.rec.get('title','')}")
            lines.append(f"Decision: {decision_line(t.dir)}")
            wt = t.rec.get("worktree")
            if wt:
                lines.append(f"Worktree: `{wt}`")
            lines.append(f"Status `{t.status}`. Review: `{t.dir.name}/review.md`")
            lines.append("")
    # preserve the human inbox verbatim
    inbox = ""
    if existing and INBOX_MARK in existing:
        inbox = existing[existing.index(INBOX_MARK):]
    if not inbox.strip():
        inbox = INBOX_MARK + "\n\nOne line per idea. Intake turns these into task records and removes them.\n"
    return "\n".join(lines) + "\n" + inbox


def _write_if_changed(p: Path, text: str) -> None:
    """Idempotent: an unchanged view must not touch the file (journal mode commits what is dirty)."""
    if p.exists() and p.read_text(encoding="utf-8") == text:
        return
    p.write_text(text, encoding="utf-8")


def write_queues(root: Path, g: Graph, weights: dict, limits: dict) -> None:
    qd = root / "queues"
    qd.mkdir(exist_ok=True)
    _write_if_changed(qd / "scribers.md", render_scribers(g, weights, limits))
    op = qd / "omri.md"
    _write_if_changed(op, render_omri(g, op.read_text(encoding="utf-8") if op.exists() else None))
